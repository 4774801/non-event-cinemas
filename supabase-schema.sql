create table if not exists public.screenings (
  id bigint generated by default as identity primary key,
  title text not null,
  screening_at timestamptz not null,
  runtime text,
  year int,
  note text,
  poster_url text,
  curator text,
  is_past boolean not null default false,
  is_cancelled boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.rsvps (
  id bigint generated by default as identity primary key,
  screening_id bigint not null references public.screenings(id) on delete cascade,
  user_name text not null check (char_length(user_name) between 1 and 24),
  status text not null check (status in ('going','maybe','not_going')),
  created_at timestamptz not null default now(),
  unique(screening_id, user_name)
);

create table if not exists public.recommendations (
  id bigint generated by default as identity primary key,
  title text not null,
  reason text,
  poster_url text,
  user_name text not null check (char_length(user_name) between 1 and 24),
  votes int not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.recommendation_votes (
  recommendation_id bigint not null references public.recommendations(id) on delete cascade,
  user_name text not null,
  created_at timestamptz not null default now(),
  primary key (recommendation_id, user_name)
);

create table if not exists public.ratings (
  id bigint generated by default as identity primary key,
  screening_id bigint not null references public.screenings(id) on delete cascade,
  user_name text not null check (char_length(user_name) between 1 and 24),
  score int not null check (score between 1 and 5),
  created_at timestamptz not null default now(),
  unique(screening_id, user_name)
);

alter table public.screenings add column if not exists curator text;
alter table public.screenings add column if not exists is_cancelled boolean not null default false;
alter table public.recommendations add column if not exists is_active boolean not null default true;

alter table public.screenings enable row level security;
alter table public.rsvps enable row level security;
alter table public.recommendations enable row level security;
alter table public.recommendation_votes enable row level security;
alter table public.ratings enable row level security;

