create or replace function public.toggle_recommendation_vote(rec_id bigint, voter_name text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from public.recommendations
    where id = rec_id and is_active = true
  ) then
    return;
  end if;

  if exists (
    select 1 from public.recommendation_votes
    where recommendation_id = rec_id and user_name = voter_name
  ) then
    delete from public.recommendation_votes
    where recommendation_id = rec_id and user_name = voter_name;
  else
    insert into public.recommendation_votes(recommendation_id, user_name)
    values (rec_id, voter_name);
  end if;

  update public.recommendations
  set votes = (
    select count(*) from public.recommendation_votes
    where recommendation_id = rec_id
  )
  where id = rec_id and is_active = true;
end;
$$;

grant execute on function public.toggle_recommendation_vote(bigint, text) to anon;

